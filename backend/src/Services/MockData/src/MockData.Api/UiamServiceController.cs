using Libs.Web;
using Microsoft.AspNetCore.Http.Extensions;
using Microsoft.AspNetCore.Mvc;
using Newtonsoft.Json.Linq;
using System.Dynamic;

namespace MockData.Api
{
    [ApiController()]
    [Route("[controller]")]
    public class UiamServiceController : ControllerBase
    {
        [HttpGet("")]
        public IActionResult Get()
        {
            return new OkObjectResult(new { Message = "Welcome to the UIAM Service mock data controller " });
        }

        [HttpGet("{**catchAll}")]
        public IActionResult GetCatchAll(string catchAll)
        {
            return PostCatchAll(catchAll, new UiamRequest());
        }

        [HttpPost("{**catchAll}")]
        public IActionResult PostCatchAll(string catchAll, [FromBody] UiamRequest request)
        {
            var qs = Request.QueryString.Value;

            if (qs.Contains("debug"))
            {
                return new OkObjectResult(
                    new
                    {
                        route = Request.GetEncodedUrl(),
                        @params = qs,
                        headers = Request.Headers,
                        contentType = Request.ContentType,
                    }
                );
            }
            var paths = catchAll.Split("/").Where(s => !string.IsNullOrEmpty(s));
            request.UserId = paths.FirstOrDefault() ?? "";

            try
            {
                using (var r = new StreamReader("uiam.json"))
                {
                    string json = r.ReadToEnd();
                    var token = json.Parse();
                    var path = string.Join(".", catchAll.Split("/").Where(s => !string.IsNullOrEmpty(s)));
                    path = string.Join(".", ["getUiamData", path]);
                    var result = token.SelectToken(path);

                    if (result == null)
                    {
                        return StatusCode(400, new UiamDataResponse());
                    }

                    if (result is JArray jArray)
                    {
                        var te = CollectionHelper.GetPaginationResult(jArray, qs);
                        return new JsonResult(new UiamDataResponse(request, CollectionHelper.GetPaginationResult(jArray, qs)));
                    }
                    dynamic claimAttributesList = result.SelectToken("claimAttributesList");
                    dynamic rps = result.SelectToken("RPs");
                    return new JsonResult(new UiamDataResponse(claimAttributesList, rps));
                }
            }
            catch (Exception ex)
            {
                return StatusCode(500, new
                {
                    errorType = ex.GetType().FullName,
                    errorMessage = ex.Message,
                    innerExceptionType = ex.InnerException?.GetType().FullName,
                    innerExceptionMessage = ex.InnerException?.Message
                });
            }
        }
        public class UiamRequest
        {
            public string RequestId { get; set; } // random string generated by client
            public string UserId { get; set; } // identifier for current logged in user - User Account ID
            public List<string> RelyingPartyIDs { get; set; } // list of UIAM RP IDs
            public int AccessLogLimit { get; set; } // maximum number of access logs per RP to be returned by UIAM
            public DateTime RequestDateTime { get; set; } = DateTime.UtcNow;

            public UiamRequest()
            {
                RelyingPartyIDs = new List<string>();
            }
        }

        public class UiamDataResponse
        {
            public string ResponseToRequestId { get; set; } = Guid.NewGuid().ToString();
            public dynamic ClaimAttributesList { get; set; }
            public dynamic RPs { get; set; }

            public UiamDataResponse()
            {
            }
            public UiamDataResponse(dynamic claimAttributesList, dynamic rps) : this()
            {
                this.ClaimAttributesList = claimAttributesList;
                this.RPs = rps;
            }
        }
    }
}
